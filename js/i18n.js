LB.i18n = {
  lang: 'ar',
  t(key, vars) {
    const dict = LB.STRINGS[this.lang] || LB.STRINGS.ar;
    let s = dict[key] || (LB.STRINGS.en[key] || key);
    if (vars) Object.keys(vars).forEach(k => { s = s.replace('{' + k + '}', vars[k]); });
    return s;
  },
  set(lang) {
    this.lang = (lang === 'en') ? 'en' : 'ar';
    LB.store && LB.store.setSetting('uiLang', this.lang);
    this.apply();
  },
  dir() { return this.lang === 'ar' ? 'rtl' : 'ltr'; },
  apply() {
    const html = document.documentElement;
    html.setAttribute('lang', this.lang);
    html.setAttribute('dir', this.dir());
  }
};

/* short helper used across the app */
LB.t = (key, vars) => LB.i18n.t(key, vars);
